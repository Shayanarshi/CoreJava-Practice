package com.example;

public class ArrayTest {

	public static void main(String[] args) {
		int[] arr = new int[5];
		
		for(int i = 0;i<arr.length;i++) {
			System.out.println(arr[i] + " ");	
		}
		char [] charsArr = new char[5];
		for(int i = 0;i<charsArr.length;i++) {
			System.out.println(charsArr[i] + " ");	
		}
		
	}

}
